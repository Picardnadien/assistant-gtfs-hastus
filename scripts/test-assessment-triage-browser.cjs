// Run tests/assessment-triage.test.cjs first. All data is synthetic.
const fs=require('node:fs'),assert=require('node:assert/strict');
const {chromium}=require(process.argv[2]||'playwright');
(async()=>{
  const browser=await chromium.launch({channel:'msedge',headless:true});
  try{for(const language of ['fr','en']){
    const context=await browser.newContext({viewport:{width:1366,height:900},acceptDownloads:true}),page=await context.newPage(),errors=[];
    page.on('pageerror',e=>errors.push(e.message));let accept=false,confirmations=[];
    page.on('dialog',async d=>{confirmations.push(d.message());await(accept?d.accept():d.dismiss());});
    await page.route('https://triage.test/**',r=>r.fulfill({contentType:'text/html',body:fs.readFileSync(`tmp/assessment-triage-${language}.html`,'utf8')}));
    await page.goto('https://triage.test/report');await page.locator('#review-tutorial-close').click();
    assert.equal(await page.locator('#assessment-queue').inputValue(),'main');
    assert.equal(await page.locator('#cases article').count(),5);
    assert.equal(await page.locator('#cases [data-case-id^="unlocated-"]').count(),0);
    await page.locator('#assessment-queue').selectOption('secondary');
    assert.equal(await page.locator('#cases article').count(),3);
    await page.locator('#search').fill('missing1');
    assert.equal(await page.locator('#cases article').count(),1,'Only the unlocated stop is in the secondary list; its parent grouping stays main');
    await page.locator('#kind').selectOption('unlocated');
    assert.equal(await page.locator('#cases article').count(),1);
    const id=await page.locator('#cases [data-case-id]').getAttribute('data-case-id');
    await page.locator(`#${id} .assessment-note`).first().locator('summary').click();
    await page.locator(`[data-review-note="${id}"]`).fill('Keep individual note');
    await page.locator('#search').focus();
    await page.locator('#batch-review > summary').click();
    await page.locator('[data-batch-action="validate"]').click();
    assert.equal(await page.locator(`#${id} [data-review-validate]`).getAttribute('aria-pressed'),'false','Cancel is a no-op');
    accept=true;await page.locator('[data-batch-action="validate"]').click();
    assert.ok(confirmations.at(-1).includes('1'));
    assert.equal(await page.locator(`#${id} [data-review-validate]`).getAttribute('aria-pressed'),'true');
    await page.locator('#search').fill('missing');
    assert.equal(await page.locator('#cases article').count(),2);
    await page.locator('[data-batch-action="validate"]').click();
    const log=await page.locator('#assessment-log-body').textContent();
    assert.ok(log.includes('Keep individual note'));
    assert.equal(await page.locator('#assessment-log-body tr').count(),3,'Note plus one event for each stop');
    await page.locator('#stop-scope').selectOption('tp');
    assert.equal(await page.locator(`#${id} [data-review-validate]`).getAttribute('aria-pressed'),'false','TP scope remains independent');
    await page.locator('#stop-scope').selectOption('all');
    await page.reload();
    assert.equal(await page.locator('#assessment-queue').inputValue(),'secondary','Queue restored');
    await page.locator('#kind').selectOption('unlocated');
    assert.equal(await page.locator(`#${id} [data-review-validate]`).getAttribute('aria-pressed'),'true','Draft restored');
    await page.locator('#batch-review > summary').click();
    await page.locator('[data-batch-action="pending"]').click();
    assert.equal(await page.locator(`#${id} [data-review-validate]`).getAttribute('aria-pressed'),'false');
    assert.equal(await page.locator(`[data-review-note="${id}"]`).inputValue(),'Keep individual note');
    await page.locator(`[data-client-select="${id}"]`).check();
    const download=page.waitForEvent('download');await page.locator('#export-client-selection').click();
    const exported=await download,file=`tmp/triage-client-${language}.html`;await exported.saveAs(file);
    const html=fs.readFileSync(file,'utf8'),payload=JSON.parse(html.match(/<script id="assessment-data" type="application\/json">([\s\S]*?)<\/script>/)[1]);
    assert.equal(payload.cases.length,1);assert.equal(payload.cases[0].id,id);assert.equal(payload.presentation.queue,'all');
    assert.ok(payload.review.events.every(e=>e.id===id));
    await page.route('https://client.test/**',r=>r.fulfill({contentType:'text/html',body:html}));
    await page.goto('https://client.test/report');assert.equal(await page.locator('#cases article').count(),1);
    assert.equal(await page.locator(`[data-review-note="${id}"]`).inputValue(),'Keep individual note');
    await page.locator('#review-tutorial-close').click();await page.screenshot({path:`tmp/triage-${language}.png`,fullPage:true});
    assert.deepEqual(errors,[]);await context.close();
  }}finally{await browser.close();}
  console.log('PASS: FR/EN main/secondary lists, filtered batch approval, cancellation, pending, notes, scoped validation, browser draft, selected export and reopening.');
})().catch(e=>{console.error(e);process.exitCode=1;});
